// Builds database/seed.sql from the two datasets.
//
//   node database/build-seed.js
//
// Reads:
//   database/data/codeprep-questions.json   (included)
//   database/data/cysecqa.jsonl             (optional - see README to download)
// Writes:
//   database/seed.sql

const fs = require("node:fs");
const path = require("node:path");

const DATA = path.join(__dirname, "data");
const OUT = path.join(__dirname, "seed.sql");

const QUIZZES = [
    {
        id: 1, title: "Frontend Development", subject: "Web Development", difficulty: "medium",
        description: "JavaScript, TypeScript, React, CSS and the web platform.",
        technologies: ["javascript", "typescript", "react", "web-platform", "css"],
        cysec: { count: 4, keywords: ["browser", "website", "url", "link", "https", "download", "pop-up", "popup", "extension"] },
    },
    {
        id: 2, title: "Backend, APIs & Databases", subject: "Client-Server", difficulty: "medium",
        description: "Node.js, HTTP, SQL databases and system design.",
        technologies: ["nodejs", "http-apis", "databases-sql", "system-design"],
        cysec: { count: 5, keywords: ["data", "password", "backup", "encrypt", "database", "account", "server", "cloud"] },
    },
    {
        id: 3, title: "AI, Python & Cybersecurity", subject: "AI & Security", difficulty: "hard",
        description: "AI engineering, Python and everyday security awareness.",
        technologies: ["ai-engineering", "python"],
        cysec: { count: 20, keywords: [] }, // any remaining questions
    },
];

const TYPE_MAP = { MCQ_SINGLE: "multiple-choice", TRUE_FALSE: "true-false", SHORT_ANSWER: "short-answer" };

// ---------- SQL helpers ----------
const sql = (value) => {
    if (value === null || value === undefined) return "NULL";
    if (typeof value === "number") return String(value);
    return "'" + String(value)
        .replace(/\\/g, "\\\\")
        .replace(/'/g, "\\'")
        .replace(/\r/g, "\\r")
        .replace(/\n/g, "\\n") + "'";
};

// ---------- Load CodePrep ----------
const codeprep = JSON.parse(fs.readFileSync(path.join(DATA, "codeprep-questions.json"), "utf8")).questions;

function fromCodePrep(q) {
    const type = TYPE_MAP[q.type];
    if (type === "multiple-choice") {
        const options = q.answer.options.map((o) => o.text);
        const correct = q.answer.options.find((o) => o.id === q.answer.correctOptionId);
        return { type, text: q.prompt, options, answer: correct.text, explanation: q.explanation, source: "codeprep", ref: q.id };
    }
    if (type === "true-false") {
        return { type, text: q.prompt, options: ["True", "False"], answer: q.answer.value ? "True" : "False", explanation: q.explanation, source: "codeprep", ref: q.id };
    }
    return { type, text: q.prompt, options: [], answer: q.answer.sampleAnswer, explanation: q.explanation, source: "codeprep", ref: q.id };
}

// ---------- Load CySecQA (optional) ----------
let cysec = [];
const cysecPath = path.join(DATA, "cysecqa.jsonl");
if (fs.existsSync(cysecPath)) {
    cysec = fs.readFileSync(cysecPath, "utf8").split("\n").filter(Boolean).map((line, i) => ({ row: i, ...JSON.parse(line) }));
} else {
    console.warn("cysecqa.jsonl not found - building seed with CodePrep questions only.");
}

const usedCysec = new Set();
function pickCysec(count, keywords) {
    const picked = [];
    for (const row of cysec) {
        if (picked.length >= count) break;
        if (usedCysec.has(row.row)) continue;
        const text = String(row.Question).toLowerCase();
        if (keywords.length && !keywords.some((k) => text.includes(k))) continue;
        usedCysec.add(row.row);
        picked.push(row);
    }
    return picked.map((row) => {
        const letters = ["A", "B", "C", "D"];
        const options = letters.map((l) => String(row[l]));
        const answer = row[String(row.Answer).trim().toUpperCase()];
        return {
            type: "multiple-choice", text: row.Question, options, answer: String(answer),
            explanation: `The correct answer is: ${answer}.`, source: "cysecqa", ref: `row-${row.row}`,
        };
    });
}

// ---------- Build SQL ----------
const lines = [
    "-- Generated by database/build-seed.js - do not edit by hand.",
    "-- Questions from CodePrep (https://codeprep.dev), CC-BY-4.0.",
    "-- Cybersecurity questions from CySecQA (maleo-ai/CySecQA on Hugging Face).",
    "USE quizstack;",
    "SET FOREIGN_KEY_CHECKS = 0;",
    "TRUNCATE evaluation_results; TRUNCATE evaluation_responses;",
    "TRUNCATE question_options; TRUNCATE questions; TRUNCATE quizzes;",
    "SET FOREIGN_KEY_CHECKS = 1;",
    "",
];

let questionId = 0;
const summary = [];

for (const quiz of QUIZZES) {
    const questions = [
        ...codeprep.filter((q) => quiz.technologies.includes(q.technology) && TYPE_MAP[q.type]).map(fromCodePrep),
        ...pickCysec(quiz.cysec.count, quiz.cysec.keywords),
    ];

    lines.push(`-- ===== Quiz ${quiz.id}: ${quiz.title} =====`);
    lines.push(`INSERT INTO quizzes (id, title, subject, difficulty, description) VALUES (${[quiz.id, quiz.title, quiz.subject, quiz.difficulty, quiz.description].map(sql).join(", ")});`);

    questions.forEach((q, index) => {
        questionId++;
        lines.push(`INSERT INTO questions (id, quiz_id, position, type, text, answer, explanation, source, source_ref) VALUES (${[questionId, quiz.id, index + 1, q.type, q.text, q.answer, q.explanation, q.source, q.ref].map(sql).join(", ")});`);
        q.options.forEach((option, i) => {
            lines.push(`INSERT INTO question_options (question_id, position, option_text) VALUES (${questionId}, ${i + 1}, ${sql(option)});`);
        });
    });
    lines.push("");

    const count = (t) => questions.filter((q) => q.type === t).length;
    summary.push(`Quiz ${quiz.id} "${quiz.title}": ${questions.length} questions (MC ${count("multiple-choice")}, TF ${count("true-false")}, SA ${count("short-answer")})`);
}

fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(summary.join("\n"));
console.log(`Wrote ${OUT}`);
